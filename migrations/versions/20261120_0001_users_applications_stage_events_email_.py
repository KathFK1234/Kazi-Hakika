def _create_app_role_and_grants() -> None:
    """The app logs in as kazi_app: no superuser, no BYPASSRLS, no table ownership.

    The role starts NOLOGIN; the deploy step gives it a password
    (ALTER ROLE kazi_app LOGIN PASSWORD '...'), see README.
    """
    op.execute(
        f"""
        DO $$
        BEGIN
            IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{APP_ROLE}') THEN
                CREATE ROLE {APP_ROLE} NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
            END IF;
        END
        $$;
        """
    )
    op.execute(f"GRANT USAGE ON SCHEMA public TO {APP_ROLE}")
    op.execute(
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON {', '.join(APP_TABLES)} TO {APP_ROLE}"
    )


def _enable_rls(table: str) -> None:
    op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
    # FORCE makes the policy apply even to the table owner.
    op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
    op.execute(
        f"""
        CREATE POLICY {table}_owner ON {table}
            USING (user_id = {CURRENT_USER_ID})
            WITH CHECK (user_id = {CURRENT_USER_ID})
        """
    )


